class IconManager:
    """Utility for generating tinted vector QIcon and QPixmap objects from SVG definitions."""

    @staticmethod
    def get_pixmap(name: str, color: str = "#64748b", size: int = 24) -> QPixmap:
        """Returns a high-DPI crisp QPixmap rendered directly from SVG path data."""
        svg_template = SVG_ICONS.get(name)
        if not svg_template:
            return QPixmap()

        svg_bytes = QByteArray(svg_template.format(color=color).strip().encode("utf-8"))
        renderer = QSvgRenderer(svg_bytes)

        scale = 2
        pixmap = QPixmap(size * scale, size * scale)
        pixmap.setDevicePixelRatio(scale)
        pixmap.fill(Qt.transparent)

        painter = QPainter(pixmap)
        painter.setRenderHint(QPainter.Antialiasing)
        renderer.render(painter, QRectF(0, 0, size, size))
        painter.end()

        return pixmap

    @staticmethod
    def get_icon(name: str, color: str = "#64748b", size: int = 24) -> QIcon:
        """Returns a high-DPI QIcon rendered from SVG path data."""
        pixmap = IconManager.get_pixmap(name, color=color, size=size)
        return QIcon(pixmap)
